// Base URL for the CoinPaprika logo style, adjusted for the token's ID (which is often a slug of the name)
const getLogoUrl = (name: string, ticker: string): string => {
  const slug = `${ticker}-${name}`.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');
  return `https://static.coinpaprika.com/coin/${slug}/logo.png`;
};

